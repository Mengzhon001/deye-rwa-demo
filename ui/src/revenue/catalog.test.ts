import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { randomUUID } from "node:crypto";
import { RevenueRuntime } from "./runtime";
import { RevenueCatalog } from "./catalog";

test("published products coexist with isolated drafts, subscriptions and resets; catalog survives restart", async () => {
  process.env.REVENUE_MONITOR_LIVE = "false";
  const root = new RevenueRuntime(mkdtempSync(join(tmpdir(), "deye-catalog-")));
  const catalog = new RevenueCatalog(root); await catalog.start();
  const run = (actor: string, action: string, body = {}) => root.action(actor, action, body, randomUUID());
  await run("agent", "source", {mode:"synthetic"});
  const st = root.repo.read().stations[0];
  await run("owner", "apply", {stationId:st.id});
  const a = root.repo.read().applications[0], body={applicationId:a.id};
  await run("agent", "review", {...body,decision:"approved"});
  await run("agent", "offer", body);
  await run("trustee", "approve-offer", {...body,acceptProvisional:true});
  await run("owner", "accept", body); await run("owner", "sign", body);
  await run("agent", "admit", body);
  await run("agent", "prepare-valuation"); await run("trustee", "approve-valuation", {acceptProvisional:true});
  await run("agent", "publish");
  const applied:any = await run("investor", "apply-eligibility", {riskAccepted:true,demoAcknowledged:true});
  await run("agent", "eligible", {investor:"investor",applicationId:applied.id,eligible:true,reviewNote:"Test account declarations reviewed"});
  await run("investor", "subscribe", {amountUSDC6:"100000000"});
  const key=randomUUID();
  await assert.rejects(()=>catalog.create("owner",key),/Only the intermediary/);
  const next=await catalog.create("agent",key);
  assert.equal(await catalog.create("agent",key),next,"retry cannot deploy another product");
  const oldVault = root.repo.read().manifest!.addresses.vault, newVault=next.repo.read().manifest!.addresses.vault;
  assert.notEqual(oldVault,newVault);
  assert.equal(await root.vault.totalSubscriptions(),100000000n);
  assert.equal(await next.vault.totalSubscriptions(),0n);
  assert.equal(await next.vault.eligible(root.address("investor")),false);
  assert.equal(next.repo.read().applications.length,0);
  assert.equal((await catalog.rows("all")).length,1,"draft is excluded from investor catalog");
  assert.equal((await catalog.rows("all"))[0].distributionIntervalMonths,3);
  assert.equal((await catalog.rows("all",true)).length,2,"staff can select draft and published product");
  assert.equal(await catalog.select(oldVault),root);
  assert.equal(await catalog.select(newVault),next);
  await assert.rejects(()=>catalog.select("0x1111111111111111111111111111111111111111"),/Product not found/);
  await next.resetDemo("agent",{confirmation:"RESET_DEMO",expectedVault:newVault,idempotencyKey:randomUUID()});
  assert.equal(await root.vault.totalSubscriptions(),100000000n,"reset of another draft preserves subscription escrow");
  assert.equal(Number(await root.vault.phase()),1);
  const issue = (actor:string, action:string, body={})=>next.action(actor,action,body,randomUUID());
  await issue("owner","apply",{stationId:next.repo.read().stations[0].id});
  const newApplication={applicationId:next.repo.read().applications[0].id};
  await issue("agent","review",{...newApplication,decision:"approved"});
  await issue("agent","offer",newApplication);
  await issue("trustee","approve-offer",{...newApplication,acceptProvisional:true});
  await issue("owner","accept",newApplication);await issue("owner","sign",newApplication);
  await issue("agent","admit",newApplication);await issue("agent","prepare-valuation");
  await issue("trustee","approve-valuation",{acceptProvisional:true});await issue("agent","publish");
  assert.equal((await catalog.rows("current")).length,2,"new issuance publishes alongside the existing product");
  assert.equal(await next.vault.totalSubscriptions(),0n);
  assert.equal(await root.vault.totalSubscriptions(),100000000n);
  const restarted=new RevenueCatalog(new RevenueRuntime(root.dataDir));await restarted.start();
  assert.equal((await restarted.rows("all",true)).length,2);
  assert.equal(await (await restarted.select(oldVault)).vault.totalSubscriptions(),100000000n);
  assert.equal(readFileSync(join(root.dataDir,"products.json"),"utf8").includes(key),true);
  await assert.rejects(()=>catalog.retire("owner", oldVault), /Only the intermediary/);
  await assert.rejects(()=>catalog.retire("agent", oldVault), /End fundraising/);
  await run("agent", "fail");
  await catalog.retire("agent", oldVault);
  assert.equal((await catalog.rows("all",true)).length,1,"retired products disappear from every normal list");
  assert.equal(await (await catalog.select(oldVault)).vault.totalSubscriptions(),100000000n,"removal preserves refunds");
  const restored=new RevenueCatalog(new RevenueRuntime(root.dataDir));await restored.start();
  assert.equal((await restored.rows("all",true)).length,1);
  const retired=await restored.select(oldVault);
  assert.equal(restored.entry(retired).archived,true);
  assert.notEqual((await restored.select()).repo.read().manifest!.addresses.vault,oldVault,"public deployment chooses a current product");
  assert.throws(()=>restored.assertAction(retired,"reset"),/refund-only/);
  assert.throws(()=>restored.assertAction(retired,"subscribe"),/refund-only/);
  assert.doesNotThrow(()=>restored.assertAction(retired,"refund"));
  await (await restored.select(oldVault)).action("investor","refund",{},randomUUID());
  assert.equal(await root.vault.totalSubscriptions(),0n,"original investor can still claim full refund after restart");
  catalog.monitor.stop(); restarted.monitor.stop(); restored.monitor.stop();
});

