const now = Date.UTC(2026, 8, 17) / 1000;
const assumptions = () => ({ ...demoAssumptions('CNY'), costs: [{ id: 'ops', label: 'Maintenance', payer: 'revenue' as const, annualLocal: 1200, evidence: 'test contract' }], degradationPct: 0, availabilityPct: 100, inflationPct: 0 });
test('two revenue sources, owner saving and grid bill reconcile without discounting the pool share twice', () => {
  const a = assumptions();
  const r = monthlyRevenue(a, { generationKWh: 1000, exportKWh: 400, importKWh: 200 }, 1);
  assert.equal(r.selfUseKWh, 540);
  assert.equal(r.householdPaymentLocal, 259.2);
  assert.equal(r.exportRevenueLocal, 140);
  assert.equal(r.grossLocal, 399.2);
  assert.equal(r.assignedUSDC6, units(41.888));
  assert.equal(r.allGridBillLocal, 444);
  assert.equal(r.householdBillLocal, 379.2);
  assert.ok(Math.abs(r.householdSavingLocal - 64.8) < 1e-9);
  assert.ok(Math.abs(r.allGridBillLocal! - r.householdBillLocal! - r.householdSavingLocal) < 1e-9);
  assert.equal(r.retainedRevenueLocal, 0);
  const otherImport = monthlyRevenue(a, { generationKWh: 1000, exportKWh: 400, importKWh: 2000 }, 1);
  assert.equal(otherImport.assignedUSDC6, r.assignedUSDC6, 'Grid purchases never become project receipts or duplicate costs');
});
