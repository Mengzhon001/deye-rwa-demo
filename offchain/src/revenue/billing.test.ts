test('combined cashflow pool ledger counts monthly collections, fees and final release once', () => {
  const report = forecast(syntheticStation(now), demoAssumptions(), now);
  const purchase = amount(report.rightsValueUSDC6);
  const p = projectPool([report], { purchasePriceUSDC6: report.rightsValueUSDC6, cashUSDC6: units(purchase / 9), monthlyCostUSDC6: '1000000' });
  assert.equal(p.periods.length, 60);
  const receipts = report.rows.reduce((n,r)=>n + amount(r.assignedUSDC6),0);
  const expenses = p.periods.reduce((n,r)=>n + amount(r.feeUSDC6) + amount(r.mandatoryCostUSDC6),0);
  const paid = p.cashflows.slice(1).reduce((n,r)=>n + amount(r.valueUSDC6),0);
  assert.ok(Math.abs(paid - (purchase/9 + receipts - expenses)) < 0.0001);
  assert.ok(p.cashflows.at(-1)!.at > addMonths(now, 60), 'Final delayed receipt follows rights expiry');
  assert.ok(p.periods.filter(r=>r.month % 3).every(r=>r.payoutUSDC6 === '0'));
});

